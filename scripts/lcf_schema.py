"""
Generates src/formats/rm2k/schema.ts: the field tables of RPG Maker 2000/2003
save files, from liblcf's generator/csv/fields.csv (MIT License,
https://github.com/EasyRPG/liblcf).

    python scripts/lcf_schema.py <path to liblcf>/generator/csv/fields.csv
"""
import csv
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "formats" / "rm2k" / "schema.ts"


def main(path):
    rows = list(csv.DictReader(open(path, encoding="utf-8", newline="")))
    # Structs whose elements start with an id when they are in an array.
    with_id = sorted(
        row["Structure"]
        for row in csv.DictReader(open(Path(path).with_name("structs.csv"), encoding="utf-8", newline=""))
        if row["Type"] == "lsd" and row["Index available?"] == "1"
    )
    structs = {}
    for row in rows:
        structs.setdefault(row["Structure"], []).append(row)

    wanted, todo = set(), ["Save"]
    while todo:
        name = todo.pop()
        # Structs without chunk ids (EventCommand...) are read in a special way: left as raw bytes.
        if name in wanted or name not in structs or any(not row["Index"] for row in structs[name]):
            continue
        wanted.add(name)
        for row in structs[name]:
            # References and enums point at the game database, not at the save.
            plain = re.sub(r"(Ref|Enum)<[^>]*>", "", row["Type"])
            for token in re.findall(r"[A-Za-z_]\w*", plain):
                if token in structs:
                    todo.append(token)

    lines = [
        "// Generated by scripts/lcf_schema.py from liblcf's fields.csv (MIT License, see LICENSE-liblcf.txt).",
        "// Each field: [chunk id, name, type]. Count fields are written as [id, name, type, 'count'].",
        "export const SCHEMA: Record<string, [number, string, string, string?][]> = {",
    ]
    for name in sorted(wanted):
        fields = []
        for row in structs[name]:
            entry = f"[{int(row['Index'], 16)}, {row['Field']!r}, {row['Type']!r}"
            if row["Size Field?"] == "t":
                entry += ", 'count'"
            fields.append(entry.replace("'", '"') + "]")
        lines.append(f"  {name!r}: [{', '.join(fields)}],".replace("'", '"'))
    lines.append("};")
    lines.append("")
    lines.append("/** Structs whose array elements start with an id. */")
    lines.append("export const HAS_ID = new Set([" + ", ".join(f'"{name}"' for name in with_id) + "]);")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(wanted)} structs: {', '.join(sorted(wanted))}")
    print("written", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main(sys.argv[1])
